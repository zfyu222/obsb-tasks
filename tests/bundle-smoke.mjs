import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import * as obsidian from './obsidian-mock.mjs';
import { openPlugin } from './host.mjs';
import { encodeBoard as legacyBoard } from '../.test-build/legacy-codec.mjs';
const dom = new JSDOM('<!doctype html><body></body>', { pretendToBeVisual: true });
Object.assign(globalThis, { window: dom.window, document: dom.window.document });
const code = await readFile('dist/obsb-tasks/main.js', 'utf8'), module = { exports: {} };
assert.match(code, /Copyright \(c\) 2021 Mark/); assert.match(code, /Permission is hereby granted/);
vm.runInNewContext(code, { module, exports: module.exports, require: name => { if (name === 'obsidian') return obsidian; throw Error(`unexpected runtime dependency ${name}`); },
  document, window, crypto, TextEncoder, structuredClone, Event: dom.window.Event, HTMLElement: dom.window.HTMLElement,
  requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window), cancelAnimationFrame: dom.window.cancelAnimationFrame.bind(dom.window),
  setTimeout, clearTimeout, console });
const { plugin, view } = await openPlugin(module.exports.default);
const press = (element, key, more = {}) => element.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key, bubbles: true, cancelable: true, ...more }));
const tick = () => new Promise(resolve => setTimeout(resolve, 30));
const stage = () => view.contentEl.querySelector('.obsb-task-stage');
press(stage(), 'Tab'); await tick();
assert.equal((await plugin.store.load()).nodes.length, 1);
let input = view.contentEl.querySelector('.obsb-task-inline-title'); assert.ok(input);
input.value = '实际发布包节点'; input.dispatchEvent(new dom.window.Event('input')); press(input, 'Enter'); await tick();
assert.equal((await plugin.store.load()).nodes[0].title, '实际发布包节点');
const card = view.contentEl.querySelector('.obsb-core-node.task');
assert.equal(card.style.height, '24px'); assert.equal(card.querySelector('small'), null); assert.equal(card.dataset.importance, 'medium');
const importance = view.contentEl.querySelector('[data-field=importance]'); importance.value = 'high'; importance.dispatchEvent(new dom.window.Event('change')); await tick();
assert.equal(card.dataset.importance, 'high'); assert.match(card.title, /重要程度：高/);
assert.ok(view.contentEl.querySelector('svg.obsb-map-paths path').getAttribute('d').includes('C'));
const kind = view.contentEl.querySelector('[data-field=kind]'); kind.value = 'area'; kind.dispatchEvent(new dom.window.Event('change')); await tick();
assert.equal((await plugin.store.load()).nodes[0].kind, 'area');
press(stage(), 'z', { ctrlKey: true }); await tick(); assert.equal((await plugin.store.load()).nodes[0].kind, 'task');
const status = view.contentEl.querySelector('[data-field=status]'); status.value = 'done'; status.dispatchEvent(new dom.window.Event('change')); await tick();
const completed = view.contentEl.querySelector('[data-field=completed]');
assert.equal(completed.type, 'datetime-local');
assert.equal(new Date(completed.value).toISOString(), (await plugin.store.load()).nodes[0].completed);
completed.value = '2026-10-27T18:30'; completed.dispatchEvent(new dom.window.Event('input')); completed.dispatchEvent(new dom.window.Event('change')); await tick();
assert.equal((await plugin.store.load()).nodes[0].completed, new Date('2026-10-27T18:30').toISOString());
const path = 'Raw/任务管理/当前任务.md', before = await plugin.store.load();
const file = plugin.app.vault.getAbstractFileByPath(path), legacy = legacyBoard(before);
file.data = legacy; plugin.store.invalidate(); await view.reload();
const taskCard = [...view.contentEl.querySelectorAll('.obsb-task-card')].find(e => e.textContent.includes('实际发布包节点'));
taskCard.querySelector('button').click(); await tick();
const notes = view.contentEl.querySelector('[data-field=notes]'); notes.value = 'AI 可直接阅读 [[设计]]'; notes.dispatchEvent(new dom.window.Event('input'));
plugin.app.workspace.getLeavesOfType = () => [{ view }];
assert.ok(plugin.commands.has('migrate-markdown')); plugin.commands.get('migrate-markdown').callback(); await tick(); await tick();
assert.match(file.data, /"format":2/); assert.match(file.data, /- \[x\] 实际发布包节点/);
assert.match(file.data, /> AI 可直接阅读 \[\[设计\]\]/); assert.doesNotMatch(file.data, /obsb-node|"parent"/);
assert.ok(plugin.app.vault.getMarkdownFiles().some(f => f.path.startsWith('Raw/任务管理/格式备份/') && f.data === legacy));
await view.onClose();
console.log('Production bundle: compact nodes, live priority, layout, editing, completion and safe Markdown migration passed');
